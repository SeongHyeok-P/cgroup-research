#!/usr/bin/env bash

set -euo pipefail


# ==================================================
# 고정 실험 설정
# ==================================================

# 측정 프로그램은 CPU 2에 고정
MEASURE_CPU=2

# 메모리 방해 프로그램은
# 서로 다른 물리 코어에 하나씩 배치
HOG_CPUS=(4 6 8 10 12 14)

# 방해 프로그램 하나당 전체 데이터 크기
HOG_TOTAL_MIB=384

# 측정 프로그램의 회차당 읽기 횟수
READS_PER_ROUND=1000000

# 측정 회차 수
ROUNDS=10

# 방해 프로그램을 모두 실행한 뒤
# 안정화시키는 시간
WARMUP_SECONDS=10


# ==================================================
# 사용법 확인
# ==================================================

if [ "$#" -ne 2 ]; then
    echo "사용법:"
    echo "  $0 <측정데이터_MiB> <메모리방해수>"
    echo
    echo "예:"
    echo "  $0 1 0"
    echo "  $0 1 6"
    echo "  $0 8 0"
    echo "  $0 8 6"
    echo "  $0 64 0"
    echo "  $0 64 6"
    exit 1
fi


# 첫 번째 인자:
# 측정 프로그램 데이터 크기
SIZE_MIB="$1"

# 두 번째 인자:
# 메모리 방해 프로그램 수
COUNT="$2"


# ==================================================
# 데이터 크기 검사
# ==================================================

if ! [[ "$SIZE_MIB" =~ ^[0-9]+$ ]] ||
   [ "$SIZE_MIB" -le 0 ]; then

    echo "오류: 측정 데이터 크기는 1 이상의 정수여야 합니다."
    exit 1
fi


# ==================================================
# 방해 프로그램 수 검사
# ==================================================

case "$COUNT" in
    0|1|2|4|6)
        ;;
    *)
        echo "오류:"
        echo "메모리 방해 수는 0, 1, 2, 4, 6 중 하나여야 합니다."
        exit 1
        ;;
esac


# ==================================================
# 시작한 방해 프로그램 PID 저장
# ==================================================

PIDS=()


# ==================================================
# 종료 및 정리 함수
# ==================================================

cleanup()
{
    if [ "${#PIDS[@]}" -gt 0 ]; then

        echo
        echo "[정리] 메모리 방해 프로그램 종료"

        kill "${PIDS[@]}" 2>/dev/null || true

        wait "${PIDS[@]}" 2>/dev/null || true
    fi
}


# 정상 종료든 Ctrl+C든
# 우리가 시작한 프로그램만 정리
trap cleanup EXIT INT TERM


# ==================================================
# 실험 조건 출력
# ==================================================

echo
echo "========================================"
echo "측정 데이터 크기 : ${SIZE_MIB} MiB"
echo "메모리 방해 수   : ${COUNT}"
echo "측정 CPU          : ${MEASURE_CPU}"
echo "방해 CPU 후보     : ${HOG_CPUS[*]}"
echo "방해당 데이터     : ${HOG_TOTAL_MIB} MiB"
echo "안정화 시간       : ${WARMUP_SECONDS}초"
echo "========================================"


# ==================================================
# 메모리 방해 프로그램 시작
# ==================================================

if [ "$COUNT" -gt 0 ]; then

    echo
    echo "[1] 메모리 방해 프로그램 시작"

    for ((i = 0; i < COUNT; i++)); do

        cpu="${HOG_CPUS[$i]}"

        log_file="size_${SIZE_MIB}_hog_cpu${cpu}.log"

        taskset -c "$cpu" \
            ./mem_hog "$HOG_TOTAL_MIB" \
            > /dev/null \
            2> "$log_file" &

        pid=$!

        PIDS+=("$pid")

        echo "  CPU $cpu → PID $pid"
    done


    echo
    echo "[2] 모든 방해 프로그램 안정화 대기"
    sleep "$WARMUP_SECONDS"


    echo
    echo "[3] 방해 프로그램 생존 확인"

    for pid in "${PIDS[@]}"; do

        if ! kill -0 "$pid" 2>/dev/null; then

            echo "오류:"
            echo "PID $pid 프로그램이 종료되었습니다."
            echo "로그 파일을 확인하세요."

            exit 1
        fi
    done

    echo "  모든 방해 프로그램 정상 실행 중"
fi


# ==================================================
# 측정 시작
# ==================================================

echo
echo "[4] 측정 시작"


OUTPUT_FILE="size_${SIZE_MIB}_hog_${COUNT}.csv"


taskset -c "$MEASURE_CPU" \
    ./measure_mem \
    "$SIZE_MIB" \
    "$READS_PER_ROUND" \
    "$ROUNDS" \
    | tee "$OUTPUT_FILE"


echo
echo "[5] 결과 저장 완료"
echo "    $OUTPUT_FILE"
